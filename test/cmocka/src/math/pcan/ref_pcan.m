function ref_pcan()
	% Add path to cmocka helper export functions
	path(path(), '../../../m');

	try
		opt.describe = export_get_git_describe();
	catch
		opt.describe = 'SOF PCAN Reference Generator';
	end

	%% Phase 1: Export Golden LUTs for default and custom configurations
	export_ref_lut(opt);

	%% Phase 2 & 3: Export Golden values for WideDynamicFunction and PcanShrink
	export_ref_functions(opt);

	%% Phase 4: Export Streaming Multi-Channel Multi-Frame Test Vectors
	export_ref_streaming(opt);

	%% Phase 5: Export Corner & Edge Cases
	export_ref_corner_cases(opt);

	fprintf(1, 'All PCAN test headers exported successfully.\n');
end

function export_ref_lut(opt)
	header_fn = 'ref_pcan_lut.h';
	fh = export_headerfile_open(header_fn);
	export_comment(fh, sprintf('Generated by ref_pcan.m (%s)', opt.describe));

	% Config 1: Default TFLM configuration
	cfg1.strength = 0.95;
	cfg1.offset = 80.0;
	cfg1.gain_bits = 21;
	input_bits1 = 10;
	[lut1, ~] = pcan_gain_lookup(cfg1, input_bits1);

	export_ndefine(fh, 'PCAN_TEST_LUT1_SIZE', length(lut1));
	export_ndefine(fh, 'PCAN_TEST_LUT1_GAIN_BITS', cfg1.gain_bits);
	export_ndefine(fh, 'PCAN_TEST_LUT1_INPUT_BITS', input_bits1);
	export_vector(fh, 16, 'ref_pcan_lut1', lut1);

	% Config 2: Custom configuration (strength=0.8, offset=50.0, gain_bits=18)
	cfg2.strength = 0.8;
	cfg2.offset = 50.0;
	cfg2.gain_bits = 18;
	input_bits2 = 12;
	[lut2, ~] = pcan_gain_lookup(cfg2, input_bits2);

	export_ndefine(fh, 'PCAN_TEST_LUT2_SIZE', length(lut2));
	export_ndefine(fh, 'PCAN_TEST_LUT2_GAIN_BITS', cfg2.gain_bits);
	export_ndefine(fh, 'PCAN_TEST_LUT2_INPUT_BITS', input_bits2);
	export_vector(fh, 16, 'ref_pcan_lut2', lut2);

	fclose(fh);
	fprintf(1, 'Exported %s.\n', header_fn);
end

