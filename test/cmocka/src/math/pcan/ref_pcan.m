function export_uint32_vector(fh, vname, data)
	columns = 6;
	rows = ceil(length(data) / columns);
	fprintf(fh, '\nstatic const uint32_t %s[%d] = {\n', vname, length(data));
	i = 1;
	for j = 1:rows
		fprintf(fh, '\t%11uU,', data(i));
		i = i + 1;
		for k = 2:columns
			if i <= length(data)
				fprintf(fh, ' %11uU,', data(i));
				i = i + 1;
			end
		end
		fprintf(fh, '\n');
	end
	fprintf(fh, '};\n');
end
