function export_ref_streaming(opt)
	header_fn = 'ref_pcan_stream.h';
	fh = export_headerfile_open(header_fn);
	export_comment(fh, sprintf('Generated by ref_pcan.m (%s)', opt.describe));

	cfg.strength = 0.95;
	cfg.offset = 80.0;
	cfg.gain_bits = 21;
	cfg.smoothing_coef = 819; % 0.05 in Q14
	smoothing_bits = 10;
	input_correction_bits = 0;

	num_channels = 16;
	num_frames = 20;

	% Create deterministic synthetic test signal:
	% Baseline background noise + mid-stream bursts
	rng(42);
	input_matrix = zeros(num_channels, num_frames, 'uint32');
	for f = 1:num_frames
		for c = 1:num_channels
			noise = 50 + mod(c * 17 + f * 23, 100);
			if f >= 5 && f <= 12 && c >= 4 && c <= 10
				speech_burst = 2000 + (c * 150);
			else
				speech_burst = 0;
			end
			input_matrix(c, f) = uint32(noise + speech_burst);
		end
	end

	[output_matrix, final_noise] = pcan_process(input_matrix, cfg, smoothing_bits, input_correction_bits);

	export_ndefine(fh, 'PCAN_STREAM_NUM_CHANNELS', num_channels);
	export_ndefine(fh, 'PCAN_STREAM_NUM_FRAMES', num_frames);
	export_ndefine(fh, 'PCAN_STREAM_SMOOTHING_COEF', cfg.smoothing_coef);
	export_ndefine(fh, 'PCAN_STREAM_SMOOTHING_BITS', smoothing_bits);
	export_ndefine(fh, 'PCAN_STREAM_INPUT_CORRECTION_BITS', input_correction_bits);

	input_linear = reshape(input_matrix, [], 1);
	output_linear = reshape(output_matrix, [], 1);

	export_uint32_vector(fh, 'ref_pcan_stream_inputs', input_linear);
	export_uint32_vector(fh, 'ref_pcan_stream_outputs', output_linear);
	export_uint32_vector(fh, 'ref_pcan_stream_final_noise', final_noise);

	fclose(fh);
	fprintf(1, 'Exported %s.\n', header_fn);
end

