"""Emit a Topology2 MWW bytes control blob that selects a built-in model.

The blob is struct sof_mww_model_hdr (src/include/user/mww.h) with
model_size 0 behind struct sof_abi_hdr. The firmware loads the built-in
model whose header has the same keyword name, so a topology can choose the
keyword without carrying the model data.

Example:
    ./sof_mww_select_conf.py hi_intel \\
        ../../../../tools/topology/topology2/include/components/mww/select_hi_intel.conf
"""

import argparse
import datetime
import struct
from pathlib import Path

SOF_IPC4_ABI_MAGIC = 0x34464F53  # 'SOF4'
SOF_ABI_VERSION = (3 << 24) | (29 << 12) | 1  # 3.29.1
SOF_MWW_MODEL_MAGIC = 0x4D57574D  # 'MWWM'
SOF_MWW_MODEL_VERSION = 1
SOF_MWW_MODEL_HDR = struct.Struct("<IHHIII16sBBBBhBB5I")


def build_select_blob(name: str, threshold: float = 0.0, avg_len: int = 0) -> bytes:
    """Pack a model selection header behind struct sof_abi_hdr.

    Zero threshold and avg_len keep the trigger settings of the built-in model.
    """
    if not 1 <= len(name) <= 16:
        raise ValueError(f"keyword name '{name}' must be 1..16 characters")
    threshold_q8 = min(max(int(round(threshold * 256)), 1), 255) if threshold else 0
    if not 0 <= avg_len <= 16:
        raise ValueError(f"avg_len {avg_len} not in 0..16")
    hdr = SOF_MWW_MODEL_HDR.pack(
        SOF_MWW_MODEL_MAGIC, SOF_MWW_MODEL_VERSION, SOF_MWW_MODEL_HDR.size,
        0, 0, 0, name.encode(), 0, 0, 0, 0, threshold_q8, avg_len, 0, 0, 0, 0, 0, 0)
    abi = struct.pack("<8I", SOF_IPC4_ABI_MAGIC, 0, len(hdr), SOF_ABI_VERSION, 0, 0, 0, 0)
    return abi + hdr


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("name", help="keyword name of the built-in model, e.g. hi_intel")
    parser.add_argument("conf", type=Path, help="output Topology2 .conf file")
    parser.add_argument("--threshold", type=float, default=0.0,
                        help="trigger threshold 0..1, 0 keeps the model setting")
    parser.add_argument("--avg-len", type=int, default=0,
                        help="number of averaged probabilities, 0 keeps the model setting")
    args = parser.parse_args()

    blob = build_select_blob(args.name, args.threshold, args.avg_len)
    # Topology2 data objects take only the bytes attribute
    lines = [",".join(f"0x{b:02x}" for b in blob[i:i + 8]) for i in range(0, len(blob), 8)]
    today = datetime.date.today().strftime("%d-%b-%Y")
    args.conf.parent.mkdir(parents=True, exist_ok=True)
    with open(args.conf, "w") as f:
        f.write(f"# Exported microWakeWord built-in model selection {today}\n")
        f.write(f"# Model: {args.name}\n")
        f.write("# Auto-generated by sof_mww_select_conf.py, do not edit.\n")
        f.write(f'Object.Base.data."mww_select_{args.name}" {{\n')
        f.write('\tbytes "\n')
        f.write(",\n".join(f"\t\t{line}" for line in lines))
        f.write('"\n}\n')


if __name__ == "__main__":
    main()
